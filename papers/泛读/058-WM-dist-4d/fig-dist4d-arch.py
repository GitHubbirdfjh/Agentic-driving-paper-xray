# -*- coding: utf-8 -*-
"""自绘图：DiST-4D 的解耦时空扩散架构。

上：DiST-T —— 参考图像 + 控制信号（BEV map / 轨迹 / 3D 框 / 相机位姿）→ 未来多视角 RGB-D 序列。
下：DiST-S —— 用 metric depth 做点云重投影形成稀疏条件 → 密集 RGB-D 新视角；SCC 闭环。
"""
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch

fig, axes = plt.subplots(2, 1, figsize=(15, 9))
plt.rcParams['font.sans-serif'] = ['DejaVu Sans']

IN = "#1a6fa3"; IN_FILL = "#e2eff5"
OP = "#0b7a5c"; OP_FILL = "#dcf2e8"
OUT = "#9e5c00"; OUT_FILL = "#f8ecd2"
ALT = "#6a55c2"; ALT_FILL = "#ebe7f8"
WIRE = "#6e737b"

def box(ax, xy, w, h, label, fc, ec, fontsize=9.5):
    b = FancyBboxPatch(xy, w, h, boxstyle="round,pad=0.02", fc=fc, ec=ec, lw=1.6)
    ax.add_patch(b)
    ax.text(xy[0]+w/2, xy[1]+h/2, label, ha="center", va="center", fontsize=fontsize)
    return b

def arr(ax, p1, p2, c=WIRE):
    ax.add_patch(FancyArrowPatch(p1, p2, arrowstyle="-|>", mutation_scale=14, lw=1.5, color=c))

# ---------------- 上：DiST-T ----------------
ax = axes[0]
ax.set_title("DiST-T: temporal RGB-D forecasting  (conditioned on past frame + control signals)", fontsize=12, weight="bold", pad=10)
ax.set_xlim(0, 15); ax.set_ylim(0, 6); ax.axis("off")

box(ax, (0.4, 2.2), 2.8, 1.6, "reference image\nI_ref (6 cams)", IN_FILL, IN)
box(ax, (0.4, 4.1), 2.8, 1.3, "control signals\nS_t = {M_t, B_t, A_t, P_t}", IN_FILL, IN)
box(ax, (5.0, 1.9), 4.2, 2.4, "STDiT diffusion transformer\n28 layers, d=1152\nmulti-view / temporal / spatial blocks\n+ ControlNet-style control branch", OP_FILL, OP)
box(ax, (11.0, 1.9), 3.4, 2.4, "future RGB-D sequence\n{Z^I_t, Z^D_t}, T=17 frames\n424x800 x 6 cams\nrectified-flow v-prediction", OUT_FILL, OUT)

arr(ax, (3.2, 3.0), (5.0, 3.4))
arr(ax, (3.2, 4.75), (5.0, 4.0))
arr(ax, (9.2, 3.1), (11.0, 3.1))
ax.text(7.1, 0.9, "3D VAE (CogVideoX) encodes RGB and depth separately; low-res warmup 224x400 -> 424x800 RGB-D (mixed frame length)",
        fontsize=9, ha="center", color=WIRE, style="italic")

# ---------------- 下：DiST-S + SCC ----------------
ax = axes[1]
ax.set_title("DiST-S: spatial NVS via metric-depth projection + self-supervised cycle consistency (SCC)", fontsize=12, weight="bold", pad=10)
ax.set_xlim(0, 15); ax.set_ylim(0, 8); ax.axis("off")

box(ax, (0.3, 5.0), 3.0, 1.6, "generated RGB-D\n(DiST-T output)\nI_gen, D_gen", OUT_FILL, OUT)
box(ax, (4.9, 5.0), 3.6, 1.6, "per-frame point cloud\n(known K, extrinsics)\nproject to novel view\n-> sparse I_cond, D_cond", OP_FILL, OP)
box(ax, (10.1, 5.0), 4.4, 1.6, "DiST-S denoising UNet\n(init SVD; 8->16 in-ch,\n4->8 out-ch; cond encoder)", ALT_FILL, ALT)

box(ax, (10.1, 2.9), 4.4, 1.3, "dense novel-view\nRGB-D  I_tgt, D_tgt", ALT_FILL, ALT)
box(ax, (4.9, 2.9), 3.6, 1.3, "SCC stage 2:\nreproject to A_ori\n-> self-supervised pairs", OP_FILL, OP)
box(ax, (0.3, 2.9), 3.0, 1.3, "frozen DiST-S\n(generates A_novel\nat lateral shift tau)", IN_FILL, IN)

arr(ax, (3.3, 5.8), (4.9, 5.8))
arr(ax, (8.5, 5.8), (10.1, 5.8))
arr(ax, (12.3, 5.0), (12.3, 4.2))
arr(ax, (10.1, 3.55), (8.5, 3.55))
arr(ax, (4.9, 3.55), (3.3, 3.55))
ax.text(1.8, 4.9, "novel traj A_novel: tau in [-3m, +3m] lateral", fontsize=8.5, color=IN, ha="center",
        bbox=dict(boxstyle="round,pad=0.3", fc="white", ec=IN, alpha=0.95))
arr(ax, (1.8, 4.2), (1.8, 4.9), c=IN)

ax.text(7.5, 1.4, "Stage 1 trains on original trajectories only (n= +/-2 frame projection; +/-4 + voxel downsample as aug).\nStage 2 (SCC): A_novel views generated by frozen DiST-S, reprojected back to A_ori -> fine-tunes without GT novel views.",
        fontsize=9, ha="center", color=WIRE, style="italic")
ax.text(7.5, 0.35, "metric depth is the shared geometric bridge: learnable by diffusion (temporal) + view-consistent projection (spatial)",
        fontsize=9.5, ha="center", color=WIRE, style="italic", weight="bold")

fig.tight_layout()
